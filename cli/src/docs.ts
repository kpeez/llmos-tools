/**
 * The vault-cli skill's command reference and verb table, rendered from the
 * command registry. `llmos docs` writes them; a test renders them
 * again and compares, so the committed files never drift from `--help`.
 */

import { readFileSync } from "node:fs";
import { type Command, renderHelp } from "./cli.ts";

/** The text of the skill file at `path`, a file of this tools folder and not a vault note. */
export function readSkillFile(path: string): string {
  return readFileSync(path, "utf8");
}

export const SKILL_TABLE_START = "<!-- BEGIN GENERATED VERB TABLE -->";
export const SKILL_TABLE_END = "<!-- END GENERATED VERB TABLE -->";

function sorted(commands: readonly Command[]): Command[] {
  return [...commands].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
}

export function renderVerbTable(commands: readonly Command[]): string {
  const rows = sorted(commands).map((command) => `| \`${command.name}\` | ${command.summary} |`);
  return ["| verb | summary |", "| --- | --- |", ...rows].join("\n");
}

export function renderReference(commands: readonly Command[]): string {
  const lines = [
    "# llmos command reference",
    "",
    "Generated by `llmos docs` from the command registry in `src/commands.ts`;",
    "do not hand-edit it. Each section is the command's `--help` text.",
    "",
    "## Verbs",
    "",
    renderVerbTable(commands),
  ];
  for (const command of sorted(commands)) {
    lines.push("", `## \`${command.name}\``, "", "```text", renderHelp(command), "```");
  }
  return `${lines.join("\n")}\n`;
}

/** `skillText` with the verb table between its markers replaced. Throws without the markers. */
export function renderSkill(skillText: string, commands: readonly Command[]): string {
  const start = skillText.indexOf(SKILL_TABLE_START);
  const end = skillText.indexOf(SKILL_TABLE_END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`skill text has no ${SKILL_TABLE_START}/${SKILL_TABLE_END} markers`);
  }
  return (
    skillText.slice(0, start + SKILL_TABLE_START.length) +
    `\n${renderVerbTable(commands)}\n` +
    skillText.slice(end)
  );
}
